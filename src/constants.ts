export const findLawdCd = (address: string) => {
  if (!address) return null;
  
  // 1. Normalize both inputs by removing all spaces
  const normalizedInput = address.replace(/\s/g, "");
  
  // 2. Try direct inclusion match first (e.g. "인천서구" in "인천서구청라동")
  for (const [name, code] of Object.entries(LAWD_CD_MAP)) {
    if (normalizedInput.includes(name)) return code;
  }
  
  // 3. Handle complex case: "서울 강남구" -> ["서울", "강남구"]
  const parts = address.split(/[\s,]+/).filter(Boolean);
  
  // Try combinations of parts
  if (parts.length >= 2) {
    for (let i = 0; i < parts.length - 1; i++) {
      const combined = (parts[i].substring(0, 2) + parts[i+1]).replace(/\s/g, "");
      for (const [name, code] of Object.entries(LAWD_CD_MAP)) {
        if (combined.includes(name) || name.includes(combined)) return code;
      }
    }
  }

  // 4. Handle "광역시", "특별시" prefixes in the input
  // e.g., "인천광역시서구" should match key "인천서구"
  const cityPrefixes = ["서울특별시", "인천광역시", "부산광역시", "대구광역시", "광주광역시", "대전광역시", "울산광역시", "경기도", "충청북도", "충청남도", "전라북도", "전라남도", "경상북도", "경상남도", "제주특별자치도", "세종특별자치시"];
  const cityShortPrefixes = ["서울시", "인천시", "부산시", "대구시", "광주시", "대전시", "울산시", "경기", "충북", "충남", "전북", "전남", "경북", "경남", "제주", "세종시"];
  
  let cleanedInput = normalizedInput;
  cityPrefixes.forEach(p => { cleanedInput = cleanedInput.replace(p, p.substring(0, 2)); });
  cityShortPrefixes.forEach(p => { cleanedInput = cleanedInput.replace(p, p.substring(0, 2)); });

  for (const [name, code] of Object.entries(LAWD_CD_MAP)) {
    if (cleanedInput.includes(name)) return code;
  }

  // 5. Fallback search (find just the district name if unique enough)
  for (const [name, code] of Object.entries(LAWD_CD_MAP)) {
    // Strip early prefixes from the map key (e.g. "인천서구" -> "서구")
    const districtOnly = name.replace(/^(서울|부산|대구|인천|광주|대전|울산|경기|강원|충북|충남|전북|전남|경북|경남|제주|세종)/, "");
    if (districtOnly && districtOnly.length >= 2 && cleanedInput.includes(districtOnly)) {
      // If we found a match like "서구", check if the city also matches to avoid "Incheon Seogu" matching "Gwangju Seogu"
      const cityKey = name.substring(0, 2);
      if (cleanedInput.includes(cityKey)) return code;
      
      // If no city prefix in the key, but exact district match
      if (name === districtOnly && cleanedInput.includes(districtOnly)) return code;
    }
  }

  // 6. Last resort: check each part of the split address
  for (const part of parts) {
    const cleanedPart = part.replace(/\s/g, "");
    if (cleanedPart.length < 2) continue;
    for (const [name, code] of Object.entries(LAWD_CD_MAP)) {
      if (name.includes(cleanedPart)) return code;
    }
  }

  return null;
};
